-- CCR-PAY-ONBOARD-001：商家收单开通（拉卡拉进件 → 开通分账 → 绑定平台接收方）台账与不可变审计。
-- 契约：docs/04-api/81-Payment-Merchant-Onboarding-Contract-v0.1.md §5；裁决：docs/01-prd/44-商家收单开通拉卡拉进件裁决补充-v1.0.md。
-- 本文件与 backend/pet-boot/src/main/resources/db/settlement-migration/V44__payment_merchant_onboarding.sql 保持一字不差。

CREATE TABLE payment_merchant_onboarding (
    id                       BIGINT         NOT NULL PRIMARY KEY,
    merchant_id              BIGINT         NOT NULL COMMENT '商家 ID（每商家唯一开通记录）',
    status                   VARCHAR(32)    CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT 'DRAFT/EC_SIGNING/CONTRACT_APPLYING/CONTRACT_UNKNOWN/CONTRACT_REJECTED/LEDGER_APPLYING/LEDGER_REJECTED/BIND_APPLYING/BIND_REJECTED/ACTIVE',
    merchant_type_code       VARCHAR(32)    CHARACTER SET ascii COLLATE ascii_bin NULL COMMENT '商家类型代码快照（MCC 映射来源）',
    mer_reg_name             VARCHAR(80)    NOT NULL COMMENT '商户注册名称（营业执照名称）',
    mer_biz_name             VARCHAR(64)    NULL COMMENT '商户经营名称（空=同注册名称）',
    mer_reg_dist_code        VARCHAR(8)     CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '拉卡拉地区码',
    mer_reg_addr             VARCHAR(200)   NOT NULL COMMENT '商户详细地址（去除省市区）',
    mer_blis_name            VARCHAR(80)    NOT NULL COMMENT '营业执照名称',
    mer_blis_no_cipher       VARCHAR(512)   CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT 'AES-256-GCM 密文：营业执照号',
    mer_blis_no_masked       VARCHAR(64)    NOT NULL COMMENT '脱敏营业执照号',
    mer_blis_st_dt           DATE           NOT NULL COMMENT '营业执照开始日期',
    mer_blis_exp_dt          DATE           NOT NULL COMMENT '营业执照有效期',
    lar_name                 VARCHAR(20)    NOT NULL COMMENT '法人姓名',
    lar_id_type              VARCHAR(8)     CHARACTER SET ascii COLLATE ascii_bin NOT NULL DEFAULT '01' COMMENT '法人证件类型（固定 01 身份证）',
    lar_idcard_cipher        VARCHAR(512)   CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT 'AES-256-GCM 密文：法人证件号',
    lar_idcard_masked        VARCHAR(64)    NOT NULL COMMENT '脱敏法人证件号',
    lar_idcard_st_dt         DATE           NOT NULL COMMENT '法人证件开始日期',
    lar_idcard_exp_dt        DATE           NOT NULL COMMENT '法人证件有效期',
    lar_mobile_cipher        VARCHAR(512)   CHARACTER SET ascii COLLATE ascii_bin NULL COMMENT 'AES-256-GCM 密文：法人（签约）手机号',
    lar_mobile_masked        VARCHAR(32)    NULL COMMENT '脱敏法人（签约）手机号',
    contact_name             VARCHAR(32)    NOT NULL COMMENT '商户联系人',
    contact_mobile_cipher    VARCHAR(512)   CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT 'AES-256-GCM 密文：联系人手机号',
    contact_mobile_masked    VARCHAR(32)    NOT NULL COMMENT '脱敏联系人手机号',
    acct_type_code           VARCHAR(8)     CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '结算账户性质 57 对公 / 58 对私',
    acct_name                VARCHAR(40)    NOT NULL COMMENT '结算账户名称',
    acct_no_cipher           VARCHAR(512)   CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT 'AES-256-GCM 密文：结算账户卡号',
    acct_no_masked           VARCHAR(64)    NOT NULL COMMENT '脱敏结算账户卡号',
    acct_no_last4            CHAR(4)        CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '结算账户卡号后 4 位',
    acct_id_type             VARCHAR(8)     CHARACTER SET ascii COLLATE ascii_bin NULL COMMENT '结算人证件类型（空=同法人）',
    acct_idcard_cipher       VARCHAR(512)   CHARACTER SET ascii COLLATE ascii_bin NULL COMMENT 'AES-256-GCM 密文：结算人证件号（空=同法人）',
    acct_idcard_masked       VARCHAR(64)    NULL COMMENT '脱敏结算人证件号',
    acct_id_exp_dt           DATE           NULL COMMENT '结算人证件有效期（空=同法人）',
    openning_bank_code       VARCHAR(20)    CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '结算账户开户行号',
    openning_bank_name       VARCHAR(40)    NOT NULL COMMENT '结算账户开户行名称',
    clearing_bank_code       VARCHAR(20)    CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '结算账户清算行号',
    pos_type                 VARCHAR(32)    CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '进件 POS 类型快照',
    mcc_code                 VARCHAR(8)     CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '银联 MCC 快照',
    mer_busi_content         VARCHAR(64)    CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '经营内容字典值快照',
    settle_period            VARCHAR(8)     CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '结算周期快照',
    fee_data_json            TEXT           NOT NULL COMMENT '进件费率集合 JSON 快照',
    split_lowest_ratio       DECIMAL(5,2)   NOT NULL COMMENT '开通分账最低分账比例（百分比）快照',
    attachments_json         TEXT           NOT NULL COMMENT '附件类型 → 平台私有素材 ID 的 JSON 对象；拉卡拉 attFileId 不落库',
    cooperation_asset_id     VARCHAR(64)    CHARACTER SET ascii COLLATE ascii_bin NULL COMMENT '《分账合作协议》私有素材 ID',
    ec_order_no              VARCHAR(32)    CHARACTER SET ascii COLLATE ascii_bin NULL COMMENT '电子合同申请流水号',
    ec_apply_id              VARCHAR(64)    CHARACTER SET ascii COLLATE ascii_bin NULL COMMENT '电子合同申请受理编号',
    ec_sign_url              TEXT           NULL COMMENT '拉卡拉待签约链接（有时效，仅供运营转发商家法人）',
    ec_no                    VARCHAR(32)    CHARACTER SET ascii COLLATE ascii_bin NULL COMMENT '电子合同编号',
    ec_signed_at             DATETIME(3)    NULL COMMENT '电子合同签署完成时间（UTC）',
    contract_order_no        VARCHAR(32)    CHARACTER SET ascii COLLATE ascii_bin NULL COMMENT '进件流水号',
    contract_id              VARCHAR(32)    CHARACTER SET ascii COLLATE ascii_bin NULL COMMENT '拉卡拉进件 ID',
    contract_status          VARCHAR(32)    CHARACTER SET ascii COLLATE ascii_bin NULL COMMENT '拉卡拉 contractStatus 原值',
    contract_submitted_at    DATETIME(3)    NULL COMMENT '进件提交时间（UTC）',
    contract_decided_at      DATETIME(3)    NULL COMMENT '进件审核结论时间（UTC）',
    mer_inner_no             VARCHAR(32)    CHARACTER SET ascii COLLATE ascii_bin NULL COMMENT '拉卡拉内部商户号',
    mer_cup_no               VARCHAR(32)    CHARACTER SET ascii COLLATE ascii_bin NULL COMMENT '银联商户号（82 开头）',
    term_no                  VARCHAR(32)    CHARACTER SET ascii COLLATE ascii_bin NULL COMMENT '收单终端号',
    ledger_order_no          VARCHAR(32)    CHARACTER SET ascii COLLATE ascii_bin NULL COMMENT '开通分账流水号',
    ledger_apply_id          VARCHAR(64)    CHARACTER SET ascii COLLATE ascii_bin NULL COMMENT '开通分账受理编号',
    ledger_submitted_at      DATETIME(3)    NULL COMMENT '开通分账提交时间（UTC）',
    ledger_opened_at         DATETIME(3)    NULL COMMENT '开通分账通过时间（UTC）',
    bind_order_no            VARCHAR(32)    CHARACTER SET ascii COLLATE ascii_bin NULL COMMENT '绑定流水号',
    bind_apply_id            VARCHAR(64)    CHARACTER SET ascii COLLATE ascii_bin NULL COMMENT '绑定受理编号',
    bind_submitted_at        DATETIME(3)    NULL COMMENT '绑定提交时间（UTC）',
    bind_approved_at         DATETIME(3)    NULL COMMENT '绑定通过时间（UTC）',
    reject_reason            VARCHAR(512)   NULL COMMENT '最近一次驳回或等待超时原因',
    last_error_code          VARCHAR(64)    CHARACTER SET ascii COLLATE ascii_bin NULL COMMENT '最近一次技术错误码',
    last_error_message       VARCHAR(512)   NULL COMMENT '最近一次技术错误说明',
    submitted_at             DATETIME(3)    NULL COMMENT '首次发起时间（UTC）',
    completed_at             DATETIME(3)    NULL COMMENT '开通完成时间（UTC）',
    version                  BIGINT         NOT NULL DEFAULT 0,
    created_at               DATETIME(3)    NOT NULL,
    updated_at               DATETIME(3)    NOT NULL,
    UNIQUE KEY uk_onboarding_merchant (merchant_id),
    UNIQUE KEY uk_onboarding_ec_apply (ec_apply_id),
    UNIQUE KEY uk_onboarding_contract_order (contract_order_no),
    UNIQUE KEY uk_onboarding_mer_cup_no (mer_cup_no),
    KEY idx_onboarding_status (status, updated_at),
    CONSTRAINT ck_onboarding_status CHECK (status IN (
        'DRAFT', 'EC_SIGNING', 'CONTRACT_APPLYING', 'CONTRACT_UNKNOWN', 'CONTRACT_REJECTED',
        'LEDGER_APPLYING', 'LEDGER_REJECTED', 'BIND_APPLYING', 'BIND_REJECTED', 'ACTIVE'
    )),
    CONSTRAINT ck_onboarding_acct_type CHECK (acct_type_code IN ('57', '58')),
    CONSTRAINT ck_onboarding_lar_id_type CHECK (lar_id_type = '01'),
    CONSTRAINT ck_onboarding_split_ratio CHECK (split_lowest_ratio >= 0.00 AND split_lowest_ratio <= 100.00),
    CONSTRAINT ck_onboarding_settler CHECK (
        (acct_id_type IS NULL AND acct_idcard_cipher IS NULL AND acct_idcard_masked IS NULL AND acct_id_exp_dt IS NULL)
        OR (acct_id_type IS NOT NULL AND acct_idcard_cipher IS NOT NULL AND acct_idcard_masked IS NOT NULL AND acct_id_exp_dt IS NOT NULL)
    )
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE payment_merchant_onboarding_audit (
    id                   BIGINT          NOT NULL PRIMARY KEY,
    merchant_id          BIGINT          NOT NULL,
    onboarding_id        BIGINT          NOT NULL,
    action_type          VARCHAR(40)     CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT 'PROFILE_SAVE/SUBMIT/EC_APPLIED/EC_SIGNED/EC_UNKNOWN/CONTRACT_SUBMITTED/CONTRACT_UNKNOWN/CONTRACT_APPROVED/CONTRACT_REJECTED/CONTRACT_ADOPTED/CONTRACT_DISCARDED/LEDGER_SUBMITTED/LEDGER_OPENED/LEDGER_REJECTED/BIND_SUBMITTED/BIND_APPROVED/BIND_REJECTED/ACTIVATED/SYNC/RETRY/REVEAL/ADVANCE_FAILED',
    request_key          VARBINARY(1024) NULL COMMENT '写操作幂等键：settlement.onboarding.<action>/{operatorType}/{operatorId}/{requestId}',
    request_fingerprint  CHAR(64)        CHARACTER SET ascii COLLATE ascii_bin NULL COMMENT '写操作参数 SHA-256 指纹，用于同键异参冲突检测',
    operator_type        VARCHAR(32)     CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    operator_id          BIGINT          NULL,
    reason               VARCHAR(256)    NULL,
    detail_json          TEXT            NULL COMMENT '仅存脱敏及状态摘要，严禁记录明文敏感字段',
    created_at           DATETIME(3)     NOT NULL,
    UNIQUE KEY uk_onboarding_audit_req (request_key),
    KEY idx_onboarding_audit_merchant (merchant_id, created_at),
    KEY idx_onboarding_audit_record (onboarding_id, created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
